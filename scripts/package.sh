#!/bin/sh
set -eu
root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root"
version=${1:-dev}
case "$version" in
    ''|*[!a-zA-Z0-9._-]*) echo 'version may contain only letters, digits, dots, underscores and hyphens' >&2; exit 1 ;;
esac
if [ ! -f web/dist/index.html ]; then
    echo 'Build the dashboard first: make install && make web' >&2
    exit 1
fi
mkdir -p dist
stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT HUP INT TERM
node scripts/build-notices.mjs > "$stage/THIRD_PARTY_NOTICES.txt"
go list -m all > "$stage/GO_DEPENDENCIES.txt"
for platform in linux/amd64 linux/arm64 darwin/amd64 darwin/arm64; do
    target_os=${platform%/*}
    target_arch=${platform#*/}
    name="mihomo-capture_${version}_${target_os}_${target_arch}"
    dir="$stage/$name"
    mkdir -p "$dir/bin" "$dir/scripts"
    CGO_ENABLED=0 GOOS="$target_os" GOARCH="$target_arch" go build -trimpath -ldflags='-s -w' -o "$dir/bin/mihomo-capture" ./cmd/mihomo-capture
    cp LICENSE ./*.md config.example.yaml "$dir/"
    cp -R docs "$dir/docs"
    cp scripts/run.sh "$dir/scripts/"
    cp "$stage/THIRD_PARTY_NOTICES.txt" "$stage/GO_DEPENDENCIES.txt" "$dir/"
    tar -czf "dist/$name.tar.gz" -C "$stage" "$name"
done
# List only the archives generated by this invocation, even if dist has old ones.
if command -v sha256sum >/dev/null 2>&1; then
    (cd dist && sha256sum "mihomo-capture_${version}_"*.tar.gz) > dist/SHA256SUMS
else
    (cd dist && shasum -a 256 "mihomo-capture_${version}_"*.tar.gz) > dist/SHA256SUMS
fi
